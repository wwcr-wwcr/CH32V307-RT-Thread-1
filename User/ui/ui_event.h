/******************************************************************************
 * 文件名   : ui_event.h
 * 说明     : 触摸事件唯一入口。列表页和任务页的控件都调这一个函数。
 *
 * 为什么只留一个入口：
 *     触摸原来有两种写法——列表页把手指"伪装成按键"，任务页走 id+value 事件，
 *     两套逻辑维护成本高。现在统一成 ui_post_event(id, value)：
 *
 *         控件回调 ──ui_post_event──▶ 菜单命令队列 ──▶ UI 线程按页面分发
 *                                                        ├ 任务页：转给 on_set(id, value)
 *                                                        └ 列表页：1=上一个 2=下一个 3=进入
 *
 *     所以控件回调里只有一句 ui_post_event()，不需要知道当前在哪一页。
 *
 * 约定：
 *     id    控件编号，由各页面自己定义。同一编号在列表页和任务页含义不同没关系，
 *           两页不会同时存在，由 UI 线程按当前页面解释。
 *     value 控件当前值（滑条位置等），按钮传 0。
 ******************************************************************************/

#ifndef __UI_EVENT_H
#define __UI_EVENT_H

#include <stdint.h>

/**
 * @brief  从 UI 线程发一个触摸控件事件
 * @param  id     控件编号（页面自定义）
 * @param  value  控件数值（按钮传 0）
 * @note   非阻塞：命令队列满了就丢弃，不会卡住 LVGL
 */
void ui_post_event(uint8_t id, int32_t value);

#endif
